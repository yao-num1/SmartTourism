def stable_id(prefix: str, *parts: str) -> str:
    raw = "|".join(str(p or "") for p in parts)
    digest = hashlib.md5(raw.encode("utf-8")).hexdigest()[:16]
    return f"{prefix}_{digest}"


def parse_rating(value):
    if value in (None, ""):
        return None
    try:
        return float(value)
    except Exception:
        return None


def city_lookup():
    lookup = {}
    for adcode, name, province, *_ in CITY_SEED:
        lookup[name] = (adcode, province)
        if name.endswith("市"):
            lookup[name[:-1]] = (adcode, province)
    return lookup


def insert_cities(conn):
    now = datetime.now().isoformat(timespec="seconds")
    conn.executemany(
        """
        INSERT OR REPLACE INTO travel_cities
        (adcode, name, province, city_level, aliases, is_hot, source, updated_at)
        VALUES (?, ?, ?, ?, ?, ?, 'seed:national_city_base', ?)
        """,
        [(adcode, name, province, level, aliases, hot, now)
         for adcode, name, province, level, aliases, hot in CITY_SEED]
    )
    return len(CITY_SEED)


